import unicodedata
from typing import Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StrictInt,
    StrictStr,
    field_validator,
)

from app.core.config import settings


class ResponseRequest(BaseModel):
    customer_id: StrictInt = Field(
        gt=0,
        description="Positive customer identifier.",
    )
    prompt_id: StrictInt = Field(
        gt=0,
        description="Positive prompt identifier.",
    )
    text: StrictStr = Field(
        max_length=settings.max_input_length,
        description="Text that will be processed by the AI provider.",
    )

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    @field_validator("text")
    @classmethod
    def validate_text(cls, value: str) -> str:
        """
        NFC-normalizes and rejects control characters, mirroring
        PromptFields.validate_prompt_text (app/schemas/prompt.py) -
        found live that this customer-facing field had neither, unlike
        the internal prompt-management schemas: a null byte and a raw
        ANSI escape sequence both passed straight through untouched
        (`ResponseRequest(text="hello\\x00world\\x1b[31m")` was
        accepted as-is). \\n/\\r/\\t are legitimate in free-form text
        and explicitly exempted, same as prompt_text. Deliberately does
        NOT reject blank/whitespace-only text here - InputValidator's
        EMPTY_INPUT check downstream already owns that with its own
        error_code/message, and duplicating it here would instead
        surface as a generic schema-validation error, breaking that
        contract.
        """

        value = unicodedata.normalize("NFC", value).strip()

        if any(
            unicodedata.category(char) == "Cc" and char not in "\n\r\t"
            for char in value
        ):
            raise ValueError(
                "Input contains unsupported control characters."
            )

        return value


class SuccessResponse(BaseModel):
    status_code: Literal[200] = 200
    answer: StrictStr = Field(
        min_length=1,
        description="Generated AI response.",
    )
    prompt_tokens: StrictInt = Field(
        ge=0,
        description="Input tokens consumed by this request.",
    )
    completion_tokens: StrictInt = Field(
        ge=0,
        description="Output tokens generated by this request.",
    )
    total_tokens: StrictInt = Field(
        ge=0,
        description="Total tokens used by this request.",
    )

    model_config = ConfigDict(
        extra="forbid",
    )


class ErrorField(BaseModel):
    field: StrictStr
    message: StrictStr

    model_config = ConfigDict(
        extra="forbid",
    )


class ErrorResponse(BaseModel):
    status_code: StrictInt = Field(
        ge=400,
        le=599,
    )
    error_code: StrictStr = Field(
        min_length=1,
        max_length=100,
    )
    message: StrictStr = Field(
        min_length=1,
        max_length=500,
    )
    fields: list[ErrorField] | None = None
    request_id: StrictStr | None = None

    model_config = ConfigDict(
        extra="forbid",
    )